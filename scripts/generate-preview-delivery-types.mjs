import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

// Consumes downloaded scripts/preview-delivery-catalog.sql output only.
// Never opens a database or builds fixtures.
const input = process.argv[2];
assert.ok(input && !input.startsWith('--'), 'Usage: node scripts/generate-preview-delivery-types.mjs <catalog.json> [--check]');
const raw = readFileSync(resolve(input));
const receipt = JSON.parse(raw.toString('utf8'));
let catalog = receipt.result?.preview_delivery_catalog ?? receipt.result
  ?? receipt.preview_delivery_catalog ?? receipt[0]?.preview_delivery_catalog ?? receipt;
if (typeof catalog === 'string') catalog = JSON.parse(catalog);
const tables = ['analytics_delivery_batches', 'analytics_delivery_outbox', 'preview_link_inquiries'];
const signatures = [
  'public.accept_analytics_delivery_event(jsonb,jsonb)',
  'public.get_analytics_delivery_batch(uuid,text)',
  'public.lease_analytics_delivery_batch(text,integer,integer,uuid,integer)',
  'public.mark_analytics_delivery_published(uuid,uuid,text)',
  'public.release_analytics_delivery_publish(uuid,uuid,text)',
  'public.acquire_analytics_delivery_batch(uuid,text,uuid,integer)',
  'public.settle_analytics_delivery_batch(uuid,uuid,text,text)',
  'public.configure_preview_analytics_capture(text)',
  'public.record_preview_analytics_event(jsonb,uuid,text)',
  'public.save_preview_link_inquiry(uuid,text,text,uuid,uuid,text)',
];
const versions = ['20261009003442', '20261009003448', '20261009003454', '20261009022458'];
assert.equal(catalog.snapshot_kind, 'bltz_preview_delivery_catalog_v1');
assert.equal(catalog.project_ref, 'yevihzsgqagvuulymqum');
assert.equal(catalog.system_identifier, '7666007964130682852');
assert.equal(catalog.read_only, true);
assert.ok(Number.isFinite(Date.parse(catalog.captured_at)), 'Catalog capture time missing');
assert.deepEqual(catalog.release_versions, versions, 'Reviewed staging releases missing');
assert.deepEqual(catalog.tables.map(table => table.name).sort(), tables);
assert.deepEqual(catalog.functions.map(fn => fn.signature).sort(), [...signatures].sort());
const identifier = value => { assert.match(value, /^[a-z][a-z0-9_]*$/); return value; };
const typeFor = value => {
  const types = { uuid: 'string', text: 'string', 'timestamp with time zone': 'string',
    integer: 'number', boolean: 'boolean', jsonb: 'Json', void: 'undefined' };
  assert.ok(Object.hasOwn(types, value), `Unreviewed scoped SQL type: ${value}`);
  return types[value];
};
const snapshotHash = createHash('sha256').update(raw).digest('hex');
let output = `// GENERATED by scripts/generate-preview-delivery-types.mjs from downloaded staging catalog.\n`;
output += `// Scoped snapshot: three tables and ten public RPCs; not a full database schema.\n`;
output += `// Staging ${catalog.project_ref}; system ${catalog.system_identifier}; captured ${catalog.captured_at}.\n`;
output += `// Source JSON SHA-256: ${snapshotHash}\nimport type { Json } from "./database.generated";\n\n`;
output += 'export type PreviewDeliveryDatabase = { public: { Tables: {\n';
for (const table of [...catalog.tables].sort((a, b) => a.name.localeCompare(b.name))) {
  assert.equal(table.schema, 'public'); assert.equal(table.present, true);
  assert.ok(table.columns.length > 0); assert.ok(Array.isArray(table.relationships));
  const columns = [...table.columns].sort((a, b) => a.ordinal - b.ordinal);
  assert.equal(new Set(columns.map(column => column.name)).size, columns.length);
  output += `  ${identifier(table.name)}: {\n`;
  for (const operation of ['Row', 'Insert', 'Update']) {
    output += `    ${operation}: {\n`;
    for (const column of columns) {
      assert.equal(column.type_schema, 'pg_catalog');
      assert.equal(typeof column.nullable, 'boolean'); assert.equal(typeof column.has_default, 'boolean');
      assert.ok(['', 'a', 'd'].includes(column.identity)); assert.ok(['', 's', 'v'].includes(column.generated));
      const generated = column.generated !== '' || column.identity === 'a';
      const optional = operation === 'Update' || (operation === 'Insert' && (column.nullable || column.has_default || column.identity !== '' || generated));
      const type = operation !== 'Row' && generated ? 'never' : typeFor(column.type) + (column.nullable ? ' | null' : '');
      output += `      ${identifier(column.name)}${optional ? '?' : ''}: ${type};\n`;
    }
    output += '    };\n';
  }
  const relationships = table.relationships.map(row => {
    assert.equal(row.referenced_schema, 'public'); assert.equal(typeof row.is_one_to_one, 'boolean');
    assert.ok(row.columns.length > 0 && row.columns.length === row.referenced_columns.length);
    return { foreignKeyName: row.foreign_key_name, columns: row.columns, isOneToOne: row.is_one_to_one,
      referencedRelation: row.referenced_relation, referencedColumns: row.referenced_columns };
  });
  output += `    Relationships: ${JSON.stringify(relationships, null, 2).replace(/\n/g, '\n    ')};\n  };\n`;
}
assert.ok(catalog.tables.find(table => table.name === 'preview_link_inquiries').columns.some(column => column.name === 'analytics_session_id'));
assert.ok(catalog.tables.find(table => table.name === 'preview_link_inquiries').columns.some(column => column.name === 'analytics_environment'));
output += '}; Views: Record<string, never>; Functions: {\n';
for (const fn of [...catalog.functions].sort((a, b) => a.name.localeCompare(b.name))) {
  assert.equal(fn.present, true); assert.equal(fn.kind, 'f'); assert.equal(fn.returns_set, false);
  assert.ok(fn.argument_modes === null || fn.argument_modes.every(mode => mode === 'i'));
  assert.equal(fn.arguments.length, fn.argument_count);
  output += `  ${identifier(fn.name)}: { Args: {\n`;
  for (const [index, arg] of [...fn.arguments].sort((a, b) => a.ordinal - b.ordinal).entries()) {
    assert.equal(arg.ordinal, index + 1);
    assert.equal(arg.optional, arg.ordinal > fn.argument_count - fn.default_count);
    output += `    ${identifier(arg.name)}${arg.optional ? '?' : ''}: ${typeFor(arg.type)};\n`;
  }
  output += `  }; Returns: ${typeFor(fn.return_type)} };\n`;
}
output += '}; Enums: Record<string, never>; CompositeTypes: Record<string, never> } };\n';
const target = resolve('types/preview-delivery.generated.ts');
if (process.argv.includes('--check')) assert.equal(readFileSync(target, 'utf8').replace(/\r\n/g, '\n'), output, 'Scoped hosted types differ');
else writeFileSync(target, output);
console.log(`Verified hosted scoped catalog: ${tables.length} tables, ${signatures.length} RPCs; ${process.argv.includes('--check') ? 'checked' : 'generated'} ${target}`);
