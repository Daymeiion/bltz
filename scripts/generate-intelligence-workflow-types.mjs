import { PGlite } from '@electric-sql/pglite';
import fs from 'node:fs/promises';

const db = new PGlite();
const migration = 'supabase/migrations/20261005184406_intelligence_review_workflows.sql';
const tables = ['intelligence_review_opportunities', 'intelligence_moment_asset_links', 'intelligence_activation_drafts', 'intelligence_activation_assets', 'intelligence_workflow_history'];
try {
  await db.exec(`create role anon; create role authenticated; create role service_role; create schema private; create schema auth;
    create table auth.users(id uuid primary key); create table public.players(id uuid primary key); create table public.sports_events(id uuid primary key);
    create table public.media(id uuid primary key,player_id uuid,kind text,license_status text,public_locker_approved boolean,license_kind text);
    create table public.videos(id uuid primary key,player_id uuid);
    create table public.analytics_events(id uuid primary key default gen_random_uuid(),client_event_id uuid unique,event_name text,user_id uuid,athlete_id uuid,session_id uuid,source text,page text,properties jsonb,occurred_at timestamptz);`);
  await db.exec(await fs.readFile('supabase/migrations/20260930181840_intelligence_graph_foundation.sql', 'utf8'));
  await db.exec(await fs.readFile('supabase/migrations/20261005183837_intelligence_measured_delivery.sql', 'utf8'));
  await db.exec(await fs.readFile(migration, 'utf8'));
  await db.exec(await fs.readFile('supabase/migrations/20261005231344_production_review_environment.sql', 'utf8'));
  const { rows } = await db.query(`select table_name,column_name,data_type,udt_name,is_nullable,column_default,ordinal_position from information_schema.columns where table_schema='public' order by table_name,ordinal_position`);
  const functions = (await db.query(`select p.proname as name,p.proargnames as "argNames",oidvectortypes(p.proargtypes) as "argTypes",format_type(p.prorettype,null) as "returnType" from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.proname in ('mutate_intelligence_workflow','read_intelligence_workflows','mutate_intelligence_workflow_in_environment','read_intelligence_workflows_in_environment') order by p.proname`)).rows;
  let output = '// GENERATED by scripts/generate-intelligence-workflow-types.mjs from isolated PostgreSQL catalog.\n// Explicit development/production scope types; not a deployed schema attestation.\n';
  output += 'export type WorkflowJson = string | number | boolean | null | { [key: string]: WorkflowJson | undefined } | WorkflowJson[];\n\nexport interface IntelligenceWorkflowTables {\n';
  const typeFor = column => {
    const base = column.data_type === 'jsonb' ? 'WorkflowJson' : column.data_type === 'ARRAY' ? 'string[]' : ['numeric','smallint','integer','bigint'].includes(column.data_type) ? 'number' : column.data_type === 'boolean' ? 'boolean' : 'string';
    return base + (column.is_nullable === 'YES' ? ' | null' : '');
  };
  for (const table of tables) {
    output += `  ${table}: {\n`;
    for (const operation of ['Row','Insert','Update']) {
      output += `    ${operation}: {\n`;
      for (const column of rows.filter(row => row.table_name === table)) {
        const optional = operation === 'Update' || (operation === 'Insert' && (column.is_nullable === 'YES' || column.column_default !== null));
        output += `      ${column.column_name}${optional ? '?' : ''}: ${typeFor(column)};\n`;
      }
      output += '    };\n';
    }
    output += '  };\n';
  }
  output += '}\n\nexport interface IntelligenceWorkflowFunctions {\n';
  for (const fn of functions) {
    const args = fn.argTypes.split(', ');
    output += `  ${fn.name}: {\n    Args: {\n`;
    for (const [index,name] of fn.argNames.entries()) output += `      ${name}: ${args[index] === 'jsonb' ? 'WorkflowJson' : 'string'};\n`;
    output += '    };\n    Returns: WorkflowJson;\n  };\n';
  }
  output += '}\n';
  const target = 'types/intelligence-workflows.generated.ts';
  if (process.argv.includes('--check')) {
    if (await fs.readFile(target,'utf8') !== output) throw new Error('Workflow generated types differ; rerun generator.');
    console.log(`Verified reproducible types for ${tables.length} workflow tables and ${functions.length} RPCs.`);
  } else {
    await fs.writeFile(target,output);
    console.log(`Generated types for ${tables.length} workflow tables and ${functions.length} RPCs.`);
  }
} finally { await db.close(); }
