import { PGlite } from '@electric-sql/pglite';
import fs from 'node:fs/promises';

// Generate only the additive graph slice from its executable SQL, leaving the
// pre-existing, uncommitted Supabase database.generated.ts untouched.
const db = new PGlite();
const tables = ['intelligence_sources', 'intelligence_ingestions', 'moments', 'moment_athletes', 'intelligence_evidence'];
const migration = 'supabase/migrations/20260930181840_intelligence_graph_foundation.sql';
try {
  await db.exec('create role anon; create role authenticated; create role service_role; create schema private; create table public.players(id uuid primary key); create table public.sports_events(id uuid primary key);');
  await db.exec(await fs.readFile(migration, 'utf8'));
  await db.exec(await fs.readFile('supabase/migrations/20261001035756_intelligence_source_review.sql', 'utf8'));
  const { rows } = await db.query(`select table_name,column_name,data_type,is_nullable,column_default,ordinal_position from information_schema.columns where table_schema='public' order by table_name,ordinal_position`);
  const functions = (await db.query(`select p.proname as name,p.proargnames as "argNames",oidvectortypes(p.proargtypes) as "argTypes",format_type(p.prorettype,null) as "returnType" from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.proname='review_intelligence_observation'`)).rows;
  let output = '// GENERATED by node scripts/generate-intelligence-types.mjs from an isolated PostgreSQL catalog.\n// Additive local migration schema only; not a deployed database attestation.\n';
  output += 'export type IntelligenceJson = string | number | boolean | null | { [key: string]: IntelligenceJson | undefined } | IntelligenceJson[];\n\n';
  const typeFor = (column) => {
    const base = column.data_type === 'jsonb' ? 'IntelligenceJson'
      : ['numeric', 'smallint', 'integer', 'bigint'].includes(column.data_type) ? 'number'
        : column.data_type === 'boolean' ? 'boolean' : 'string';
    return base + (column.is_nullable === 'YES' ? ' | null' : '');
  };
  output += 'export interface IntelligenceTables {\n';
  for (const table of tables) {
    const columns = rows.filter(row => row.table_name === table);
    output += `  ${table}: {\n`;
    for (const operation of ['Row', 'Insert', 'Update']) {
      output += `    ${operation}: {\n`;
      for (const column of columns) {
        const optional = operation === 'Update' || (operation === 'Insert' && (column.is_nullable === 'YES' || column.column_default !== null));
        output += `      ${column.column_name}${optional ? '?' : ''}: ${typeFor(column)};\n`;
      }
      output += '    };\n';
    }
    output += '  };\n';
  }
  output += '}\n';
  output += '\nexport interface IntelligenceFunctions {\n';
  for(const fn of functions){
    const args=fn.argTypes.split(', ');
    output += `  ${fn.name}: {\n    Args: {\n`;
    for(const [index,name] of fn.argNames.entries())output += `      ${name}: ${args[index]==='jsonb'?'IntelligenceJson':'string'};\n`;
    output += `    };\n    Returns: ${fn.returnType==='jsonb'?'IntelligenceJson':'unknown'};\n  };\n`;
  }
  output += '}\n';
  const attestationIndex=process.argv.indexOf('--attest-catalog');
  if(attestationIndex!==-1){
    const file=JSON.parse(await fs.readFile(process.argv[attestationIndex+1],'utf8'));
    const catalog=file.rows?.[0]?.intelligence_graph_catalog ?? file.intelligence_graph_catalog ?? file;
    const expectedColumns=rows.filter(row=>tables.includes(row.table_name));
    const normalize=values=>JSON.stringify(values.map(row=>Object.fromEntries(Object.entries(row).sort(([a],[b])=>a.localeCompare(b)))));
    if(normalize(catalog.columns)!==normalize(expectedColumns)||normalize(catalog.functions)!==normalize(functions))throw new Error('Deployed additive schema catalog does not match generated migration types');
    console.log(`Attested exact deployed columns and RPC signature from ${process.argv[attestationIndex+1]}`);
  }
  if (process.argv.includes('--check')) {
    const existing = await fs.readFile('types/intelligence.generated.ts', 'utf8');
    if (existing !== output) throw new Error('Generated Intelligence types differ; rerun node scripts/generate-intelligence-types.mjs');
    console.log(`Verified reproducible generated types for ${tables.length} graph tables`);
  } else {
    await fs.writeFile('types/intelligence.generated.ts', output);
    console.log(`Generated ${tables.length} graph table types from ${migration}`);
  }
} finally { await db.close(); }
