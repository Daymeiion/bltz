import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
// Consumes the read-only downloaded staging RPC catalog. No network or fixtures.
const input=process.argv[2];
assert.ok(input&&!input.startsWith('--'),'Usage: node scripts/generate-preview-invitation-email-types.mjs <catalog.json> [--check]');
const raw=readFileSync(resolve(input));
const receipt=JSON.parse(raw.toString('utf8').replace(/^\uFEFF/,''));
let catalog=receipt.rows?.[0]?.preview_invitation_email_catalog??receipt.preview_invitation_email_catalog??receipt;
if(typeof catalog==='string')catalog=JSON.parse(catalog);
const signatures=[
 'public.prepare_preview_invitation_email(uuid,uuid,uuid,text)',
 'public.begin_preview_invitation_email(uuid,text)',
 'public.settle_preview_invitation_email(uuid,text,text,text)',
 'public.pending_preview_invitation_email_checks(text)',
 'public.preview_invitation_email_report(uuid,text)',
 'public.record_preview_invitation_dsn(uuid,text,text,text,text,text,text,timestamp with time zone)',
];
assert.equal(catalog.snapshot_kind,'bltz_preview_invitation_email_catalog_v1');
assert.equal(catalog.project_ref,'yevihzsgqagvuulymqum');
assert.equal(catalog.system_identifier,'7666007964130682852');
assert.equal(catalog.read_only,true);
assert.equal(catalog.release_version,'20261011213800');
assert.ok(Number.isFinite(Date.parse(catalog.captured_at)));
assert.deepEqual(catalog.functions.map(fn=>fn.signature).sort(),[...signatures].sort());
const localMigration=readFileSync(resolve('supabase/migrations/20261011213800_preview_invitation_email.sql'));
assert.equal(catalog.migration_source_sha256,createHash('sha256').update(localMigration).digest('hex'),'Hosted migration differs from reviewed local source');
const identifier=value=>{assert.match(value,/^[a-z][a-z0-9_]*$/);return value;};
const typeFor=value=>{const types={uuid:'string',text:'string','timestamp with time zone':'string',jsonb:'Json'};assert.ok(Object.hasOwn(types,value),`Unreviewed scoped SQL type: ${value}`);return types[value];};
// PostgreSQL catalog does not expose argument nullability. These two nullable
// inputs follow the reviewed migration contract; required IDs remain non-null.
const nullableArgs=new Set(['prepare_preview_invitation_email.p_contact','settle_preview_invitation_email.p_failure_code']);
let output='// GENERATED by scripts/generate-preview-invitation-email-types.mjs from downloaded staging catalog.\n';
output+='// Scoped snapshot: six public RPCs only. Private recipient/DSN tables are deliberately excluded.\n';
output+=`// Staging ${catalog.project_ref}; system ${catalog.system_identifier}; captured ${catalog.captured_at}.\n`;
output+=`// Source catalog JSON SHA-256: ${createHash('sha256').update(raw).digest('hex')}\n`;
output+=`// Verified migration source SHA-256: ${catalog.migration_source_sha256}\nimport type { Json } from "./database.generated";\n\n`;
output+='export type PreviewInvitationEmailDatabase = { public: { Tables: Record<string, never>; Views: Record<string, never>; Functions: {\n';
for(const fn of [...catalog.functions].sort((a,b)=>a.name.localeCompare(b.name))){
 assert.equal(fn.present,true);assert.equal(fn.kind,'f');assert.equal(fn.returns_set,false);assert.equal(fn.return_type,'jsonb');
 assert.ok(fn.argument_modes===null||fn.argument_modes.every(mode=>mode==='i'));assert.equal(fn.arguments.length,fn.argument_count);
 output+=`  ${identifier(fn.name)}: { Args: {\n`;
 for(const [index,arg] of [...fn.arguments].sort((a,b)=>a.ordinal-b.ordinal).entries()){
  assert.equal(arg.ordinal,index+1);assert.equal(arg.optional,arg.ordinal>fn.argument_count-fn.default_count);
  output+=`    ${identifier(arg.name)}${arg.optional?'?':''}: ${typeFor(arg.type)}${nullableArgs.has(`${fn.name}.${arg.name}`)?' | null':''};\n`;
 }
 output+='  }; Returns: Json };\n';
}
output+='}; Enums: Record<string, never>; CompositeTypes: Record<string, never> } };\n';
const target=resolve('types/preview-invitation-email.generated.ts');
if(process.argv.includes('--check'))assert.equal(readFileSync(target,'utf8').replace(/\r\n/g,'\n'),output,'Scoped hosted RPC types differ');
else writeFileSync(target,output);
console.log(`Verified hosted scoped invitation catalog: ${signatures.length} RPCs; ${process.argv.includes('--check')?'checked':'generated'} types/preview-invitation-email.generated.ts`);
